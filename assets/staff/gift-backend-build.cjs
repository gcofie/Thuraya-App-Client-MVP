'use strict';

const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = __dirname;
const source = fs.readFileSync(path.join(root, 'app.js'), 'utf8').replace(/\r\n/g, '\n');
function between(start, end) {
    const from = source.indexOf(start), to = source.indexOf(end, from + start.length);
    assert.ok(from >= 0 && to > from, `Shared checkout source boundary: ${start}`);
    return source.slice(from, to);
}
const marker = source.indexOf('window.__TH_SERVICE_SNAPSHOT_HELPERS_PHASE_1A__');
const start = source.lastIndexOf('(function(){', marker);
const end = source.indexOf('})();', marker) + 5;
assert.ok(marker > 0 && start > 0 && end > marker);
// Package the certified pure helpers without evaluating application source at runtime.
const financial = source.slice(start, end);
const group = between('function gb_money(v)', 'async function gb_getGroupJobs(') +
    between('function gb_groupReadyJobs(', 'function gb_taxHtmlForPlan(');
const output = `'use strict';\n// Generated by gift-backend-build.cjs from shared Staff financial evidence helpers.\nconst window = {};\n${financial}\n${group}\nmodule.exports = { normalize: source => window.thNormalizeCheckoutFinancials(source, { warn: false }), totals: gb_checkoutTotals, plan: gb_computeCheckoutPlan, isGroup: gb_isGroup, evidence: window.thFinancialEvidence, resolveMode: window.thResolveTaxPricingMode, allocateShares: window.thAllocateMoneyShares, transactionPolicy: window.thTransactionTaxPolicy };\n`;
const files = new Map([
    ['functions/gift-checkout-policy.generated.js', output],
    ['functions/gift-card-model.generated.js', fs.readFileSync(path.join(root, 'gift-card-model.js'), 'utf8').replace(/\r\n/g, '\n')]
]);
for (const [name, text] of files) {
    const file = path.join(root, name);
    if (process.argv.includes('--check')) assert.equal(fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n'), text, `${name} differs from its certified source`);
    else fs.writeFileSync(file, text);
}
console.log(`Gift shared-source ${process.argv.includes('--check') ? 'verification' : 'packaging'} PASS (${files.size} files)`);
